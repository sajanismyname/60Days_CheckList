export function getCurriculumDay(dayNumber: number): DayCurriculum {
  const found = CURRICULUM_DAYS.find((d) => d.day === dayNumber);
  if (found) return found;
  return CURRICULUM_DAYS[0];
}

export function getWeekForDay(dayNumber: number): WeekInfo {
  const week = WEEKS_INFO.find((w) => w.days.includes(dayNumber));
  if (week) return week;
  return WEEKS_INFO[0];
}
